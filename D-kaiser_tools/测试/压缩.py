#!/usr/bin/env python3
# -*- coding: utf-8 -*-

import os
import zipfile
import tarfile
import io

# ================= 核心配置 =================
OUTPUT_DIR = "test_media/archives"
TXT_NAME = "简介.txt"

ARCHIVES = {
    "ZIP": {
        "ext": "zip",
        "inventor": "Phil Katz (PKWARE)",
        "year": "1989",
        "algo": "DEFLATE",
        "desc": "The most universal archive format. Supports lossless compression. Stores multiple files and directories in a single container. Natively supported by almost all operating systems."
    },
    "TAR": {
        "ext": "tar",
        "inventor": "Unix / POSIX",
        "year": "1979",
        "algo": "None (Container only)",
        "desc": "Tape Archive. Concatenates files into a single stream without compression. Preserves Unix permissions, ownership, and timestamps. Usually paired with gzip/xz."
    },
    "GZIP": {
        "ext": "tar.gz",
        "inventor": "Jean-loup Gailly & Mark Adler",
        "year": "1992",
        "algo": "DEFLATE",
        "desc": "Standard compression for Linux/Unix. Fast compression and decompression. Widely used for source code distribution and web content encoding."
    },
    "BZIP2": {
        "ext": "tar.bz2",
        "inventor": "Julian Seward",
        "year": "1996",
        "algo": "Burrows-Wheeler + Huffman",
        "desc": "Provides better compression ratio than GZIP but is significantly slower. Uses block-sorting text compression algorithm. Common in older Linux distros."
    },
    "XZ": {
        "ext": "tar.xz",
        "inventor": "Lasse Collin & Igor Pavlov",
        "year": "2009",
        "algo": "LZMA2",
        "desc": "High-compression format based on LZMA2. Offers the best compression ratio among standard tools. Common for Linux kernel and package distribution."
    }
}
# ============================================

def generate_text(fmt, data):
    """生成简介文本内容"""
    return f"""Format: {fmt}
Extension: .{data['ext']}
Inventor: {data['inventor']}
Year: {data['year']}
Algorithm: {data['algo']}
Compression: Lossless

Introduction:
{data['desc']}

Generated by ZeroTermux Media Test Suite.
"""

def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    print(f"[*] Generating archive files in '{OUTPUT_DIR}' ...")
    
    # 1. 生成 ZIP
    content = generate_text("ZIP", ARCHIVES["ZIP"]).encode('utf-8')
    zip_path = os.path.join(OUTPUT_DIR, "sample.zip")
    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(TXT_NAME, content)
    size_kb = os.path.getsize(zip_path) / 1024
    print(f"    [+] ZIP   -> sample.zip ({size_kb:.1f} KB)")

    # 2. 生成 TAR / GZ / BZ2 / XZ
    mode_map = {
        "TAR": "w",
        "GZIP": "w:gz",
        "BZIP2": "w:bz2",
        "XZ": "w:xz"
    }
    
    for fmt in ["TAR", "GZIP", "BZIP2", "XZ"]:
        data = ARCHIVES[fmt]
        ext = data['ext']
        mode = mode_map[fmt]
        filename = f"sample.{ext}"
        filepath = os.path.join(OUTPUT_DIR, filename)
        
        with tarfile.open(filepath, mode) as tf:
            text_data = generate_text(fmt, data).encode('utf-8')
            info = tarfile.TarInfo(name=TXT_NAME)
            info.size = len(text_data)
            # 将文本内容写入 tar 包
            tf.addfile(info, io.BytesIO(text_data))
            
        size_kb = os.path.getsize(filepath) / 1024
        print(f"    [+] {fmt:<5} -> {filename} ({size_kb:.1f} KB)")

    print("\n[*] Done! All archive formats generated successfully.")

if __name__ == "__main__":
    main()